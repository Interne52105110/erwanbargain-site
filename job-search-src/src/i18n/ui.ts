/** Directory the study is published under, without trailing slash (e.g. "/job-search"). */
export const base = import.meta.env.BASE_URL.replace(/\/$/, '');

/** Localised path: English lives at the study root, French under /fr. */
export function href(lang: Lang, route: string): string {
  const clean = route === '/' ? '/' : `/${route.replace(/^\/|\/$/g, '')}/`;
  return base + (lang === 'en' ? clean : `/fr${clean}`);
}
